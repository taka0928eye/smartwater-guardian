import React from 'react';
import type { WorkOrder } from '../../types/api';

interface WorkOrderModalProps {
  isOpen: boolean;
  onClose: () => void;
  workOrder: WorkOrder | null;
}

export const WorkOrderModal: React.FC<WorkOrderModalProps> = ({
  isOpen,
  onClose,
  workOrder,
}) => {
  if (!isOpen || !workOrder) return null;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/50 p-4">
      <div className="w-full max-w-2xl rounded-lg bg-white p-6 shadow-xl">
        <div className="flex items-center justify-between border-b pb-3">
          <h2 className="text-lg font-bold text-gray-900">作業指示書 (Work Order)</h2>
          <button
            onClick={onClose}
            className="text-gray-400 hover:text-gray-600"
            type="button"
          >
            ✕
          </button>
        </div>

        <div className="mt-4 space-y-4 text-sm text-gray-700">
          <div>
            <span className="font-semibold">緊急度:</span> {workOrder.urgency}
          </div>
          <div>
            <span className="font-semibold">概算見積合計:</span> ¥{workOrder.totalEstimateYen.toLocaleString()}
          </div>
          <div>
            <span className="font-semibold">想定作業時間:</span> {workOrder.estimatedDurationHours}時間 ({workOrder.requiredWorkers}名)
          </div>
        </div>

        {/* 原価表示フッター脚註 (FR-6) */}
        <div className="mt-6 pt-3 border-t border-gray-100 text-xs text-gray-500 flex justify-between items-center">
          {workOrder.source === 'fallback' ? (
            <span>※ 本起票のAPI原価: <strong>LLM未使用（規定ルールによる算出）</strong></span>
          ) : (
            <span>
              ※ 本起票のAPI原価: <strong>¥{workOrder.costYen?.toFixed(2) ?? '0.00'}</strong>
              {workOrder.isEstimated && ' (概算)'}
              {workOrder.model && ` (モデル: ${workOrder.model})`}
              {workOrder.latencyMs !== undefined && ` [${workOrder.latencyMs}ms]`}
            </span>
          )}
        </div>
      </div>
    </div>
  );
};
